export const DICTIONARIES: Record<Lang, Record<Key, string>> = { en, es };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let out = DICTIONARIES[lang][key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) out = out.replaceAll(`{${name}}`, String(value));
  }
  return out;
}

export const LANG_COOKIE = "fl_lang";

export function asLang(value: string | undefined | null): Lang {
  return value === "es" ? "es" : "en";
}
